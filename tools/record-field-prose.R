#!/usr/bin/env Rscript
# Write `tests/testthat/fixtures/field-prose.yml` from the engine's schema.
#
# What that file is: an acknowledgement, one line per configuration field the engine
# describes, saying that R's hand-written `@param` for it was read against the engine's text
# as it is now. When the engine rewrites a description the digest stops matching and the
# test fails naming the field - which is the only moment anybody has a reason to re-read the
# R prose.
#
# This is the half of platypus#135 that the presence test cannot do. `seed` was present on
# both sides and stale on one for several releases: the engine's description grew two
# sentences about where the guarantee stops while R's one-sentence `@param` stayed as it
# was. Nothing failed, because nothing was comparing.
#
# Run it from the package root with the pinned engine reachable:
#
#     Rscript tools/record-field-prose.R
#
# It prints every field whose digest moved, and that list is the work: re-read each one's R
# prose before committing the new file. Regenerating without reading is how a ledger becomes
# a rubber stamp.

# The source tree, never the installed package. The first run of this script reported
# `engine 0.8.0a8` from a library left two pins behind, which would have written a ledger of
# an engine nobody is using - `JOURNAL.md` §4bh, the same trap in its fourth costume.
if (file.exists("DESCRIPTION")) {
  pkgload::load_all(".", quiet = TRUE)
} else {
  stop("run this from the package root, so the sources are what gets read")
}

# The extraction lives with the tests, so the generator and the test cannot drift apart.
`%||%` <- platypus:::`%||%`
source("tests/testthat/helper-rd.R")
source("tests/testthat/helper-field-prose.R")

described <- described_field_prose()
locations <- argument_locations(tools::Rd_db(dir = "."))
before <- recorded_field_prose()

recorded <- if (is.null(before)) {
  character(0)
} else {
  stats::setNames(
    vapply(before$fields, function(entry) entry$engine_digest, character(1)),
    vapply(before$fields, function(entry) entry$field, character(1))
  )
}

lines <- c(
  "# Generated by tools/record-field-prose.R - do not edit by hand.",
  "#",
  "# One entry per configuration field the engine describes. The digest covers every",
  "# description that name carries in the schema, and its presence here means: R's prose for",
  "# this field was read against that text. `documented_in` says which help topics carry it.",
  "#",
  "# A digest that no longer matches is not the engine's failure. It is a question - does R's",
  "# prose still say the right thing? - asked at the only moment anybody would ask it.",
  sprintf("engine: %s", platypus_status()$engine_version),
  "fields:"
)

for (field in names(described)) {
  topics <- locations[[field]]
  lines <- c(
    lines,
    sprintf("  - field: %s", field),
    sprintf("    engine_digest: %s", described[[field]]),
    sprintf("    documented_in: [%s]", paste(sort(topics), collapse = ", "))
  )
}

writeLines(lines, "tests/testthat/fixtures/field-prose.yml")

added <- setdiff(names(described), names(recorded))
shared <- intersect(names(described), names(recorded))
changed <- shared[described[shared] != recorded[shared]]
gone <- setdiff(names(recorded), names(described))

cat(sprintf("tests/testthat/fixtures/field-prose.yml: %d fields, engine %s\n",
            length(described), platypus_status()$engine_version))
if (length(added)) cat("new to the schema:", paste(added, collapse = ", "), "\n")
if (length(gone)) cat("gone from the schema:", paste(gone, collapse = ", "), "\n")
if (length(changed)) {
  cat("the engine rewrote these - re-read R's prose for each:\n")
  for (field in changed) {
    where <- locations[[field]]
    cat(sprintf("  %-22s %s\n", field,
                if (length(where)) paste(sort(where), collapse = ", ") else "documented nowhere"))
  }
}
